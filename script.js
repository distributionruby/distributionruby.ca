function setLanguage(language) {
  const copy = translations[language];
  document.documentElement.lang = language === 'fr' ? 'fr-CA' : 'en-CA';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = copy[element.dataset.i18n];
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = copy[element.dataset.i18nHtml];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', copy[element.dataset.i18nAria]);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', copy[element.dataset.i18nAlt]);
  });
  document.querySelectorAll('[data-i18n-href]').forEach((element) => {
    element.setAttribute('href', copy[element.dataset.i18nHref]);
  });
  document.querySelector('meta[name="description"]').setAttribute('content', copy.description);
  document.querySelectorAll('.language-button').forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

document.querySelectorAll('.language-button').forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

const revealElements = document.querySelectorAll(
  '.hero-copy > *, .logo-stage, .about > div, .about > p, .section-heading, .values article, .values .value-shop, .contact > div'
);

revealElements.forEach((element, index) => {
  element.classList.add('reveal');
  element.style.setProperty('--reveal-delay', `${Math.min(index % 4, 3) * 80}ms`);
});

if ('IntersectionObserver' in window && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.14 });

  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add('is-visible'));
}

